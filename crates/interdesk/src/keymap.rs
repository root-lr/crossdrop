pub mod hid {
    pub const ESCAPE: u16 = 0x29;
    pub const LEFT_CTRL: u16 = 0xE0;
    pub const LEFT_SHIFT: u16 = 0xE1;
    pub const LEFT_ALT: u16 = 0xE2;
    pub const LEFT_GUI: u16 = 0xE3;
    pub const RIGHT_CTRL: u16 = 0xE4;
    pub const RIGHT_SHIFT: u16 = 0xE5;
    pub const RIGHT_ALT: u16 = 0xE6;
    pub const RIGHT_GUI: u16 = 0xE7;
}

fn find(
    col: impl Fn(&(u16, u16, u16, u16)) -> u16,
    value: u16,
    out: impl Fn(&(u16, u16, u16, u16)) -> u16,
) -> Option<u16> {
    if value == NONE || value == 0 {
        return None;
    }
    KEYS.iter().find(|k| col(k) == value).map(out).filter(|v| *v != NONE)
}

pub fn hid_from_evdev(code: u16) -> Option<u16> {
    find(|k| k.1, code, |k| k.0)
}

pub fn evdev_from_hid(hid: u16) -> Option<u16> {
    find(|k| k.0, hid, |k| k.1)
}

/// `scan` is the set-1 scan code, `| 0xE000` for extended keys.
pub fn hid_from_windows(scan: u16) -> Option<u16> {
    find(|k| k.2, scan, |k| k.0)
}

pub fn windows_from_hid(hid: u16) -> Option<u16> {
    find(|k| k.0, hid, |k| k.2)
}

pub fn hid_from_mac(keycode: u16) -> Option<u16> {
    // 0x00 is a real macOS key code (A), so it bypasses `find`'s zero check.
    KEYS.iter().find(|k| k.3 == keycode && k.3 != NONE).map(|k| k.0)
}

pub fn mac_from_hid(hid: u16) -> Option<u16> {
    KEYS.iter().find(|k| k.0 == hid).map(|k| k.3).filter(|v| *v != NONE)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn every_column_is_unique() {
        for (name, col) in [("hid", 0), ("evdev", 1), ("windows", 2), ("mac", 3)] {
            let mut seen = HashSet::new();
            for k in KEYS {
                let v = [k.0, k.1, k.2, k.3][col];
                if v != NONE {
                    assert!(seen.insert(v), "duplicate {name} code {v:#x}");
                }
            }
        }
    }

    #[test]
    fn roundtrips() {
        for k in KEYS {
            assert_eq!(hid_from_evdev(evdev_from_hid(k.0).unwrap()), Some(k.0));
            assert_eq!(hid_from_windows(windows_from_hid(k.0).unwrap()), Some(k.0));
            if let Some(mac) = mac_from_hid(k.0) {
                assert_eq!(hid_from_mac(mac), Some(k.0));
            }
        }
    }

    #[test]
    fn known_keys() {
        // 'A' everywhere
        assert_eq!(hid_from_evdev(30), Some(0x04));
        assert_eq!(hid_from_windows(0x1E), Some(0x04));
        assert_eq!(hid_from_mac(0x00), Some(0x04));
        // Linux codes below 89 equal Windows set-1 scan codes for non-extended keys.
        for k in KEYS {
            if k.2 < 0xE000 && k.1 < 89 {
                assert_eq!(k.1, k.2, "hid {:#x}", k.0);
            }
        }
        assert_eq!(windows_from_hid(hid::RIGHT_ALT), Some(0xE038));
        assert_eq!(mac_from_hid(hid::LEFT_GUI), Some(0x37));
        // F13 and F20, which Mac keyboards have, and F24, which they do not.
        assert_eq!(hid_from_mac(0x69), Some(0x68));
        assert_eq!(hid_from_evdev(190), Some(0x6F));
        assert_eq!(mac_from_hid(0x73), None);
        assert_eq!(hid_from_windows(0x76), Some(0x73));
    }
}
